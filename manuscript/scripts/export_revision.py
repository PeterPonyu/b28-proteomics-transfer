#!/usr/bin/env python3
"""Promote verified 2026-09-22 predictions into the original B28 article.

No model fit or data download. All model evidence remains byte-identical in
analysis/revision_20260922; current plot-data and TeX tables are derived here.
"""
from __future__ import annotations

import csv
import hashlib
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from sklearn.metrics import brier_score_loss, log_loss, roc_auc_score

CAP = Path(__file__).resolve().parents[2]
MAN = CAP / "manuscript"
BASE = CAP / "analysis/revision_20260922/candidate-v1"
SIDE = BASE.parent / "candidate-v2-side-studies"
PD = MAN / "figures/plotdata"
TABLES = MAN / "tables"
COHORTS = ("Ccrcc", "Luad", "Ucec", "Hnscc", "Lscc", "Pdac")
PROTOCOLS = {"sample_random": "random_5fold", "patient_grouped": "patient_gkf",
             "leave_one_cohort_out": "logo_xgb"}


def read(path):
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(name, rows):
    with (PD/name).open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def tex(name, lines):
    (TABLES/name).write_text("% Generated by scripts/export_revision.py; do not edit.\n" +
                             "\n".join(lines) + "\n")


def metrics(rows, field="p"):
    y = np.array([int(r["y"]) for r in rows])
    p = np.array([float(r[field]) for r in rows])
    ece = 0.
    for j in range(10):
        mask = (p >= j/10) & ((p < (j+1)/10) if j < 9 else (p <= 1))
        if mask.any():
            ece += mask.mean() * abs(p[mask].mean()-y[mask].mean())
    return dict(n=len(y), auc=float(roc_auc_score(y, p)), ece=float(ece),
                brier=float(brier_score_loss(y, p)), log_loss=float(log_loss(y, p)))


def main():
    PD.mkdir(exist_ok=True)
    TABLES.mkdir(exist_ok=True)
    for directory, qa_name in ((BASE, "candidate-QA.json"), (SIDE, "QA.json")):
        qa = json.loads((directory/qa_name).read_text())
        for name, expected in qa["output_sha256"].items():
            if sha(directory/name) != expected:
                raise AssertionError(f"Verified prediction evidence changed: {name}")
    result = json.loads((BASE/"candidate-results.json").read_text())
    main_results = result["results"]
    sides = json.loads((SIDE/"results.json").read_text())
    pred = read(BASE/"predictions.csv")
    identity = read(BASE/"sample-identity-and-folds.csv")
    recal = read(BASE/"candidate-recalibration.csv")
    risk = read(BASE/"candidate-riskcoverage.csv")
    rec = json.loads((BASE/"candidate-recalibration-summary.json").read_text())
    logo = main_results["accession"]["leave_one_cohort_out"]
    if len(identity) != 1191 or len({r["patient_id"] for r in identity}) != 719:
        raise AssertionError("Corrected identity inventory changed")
    by_patient = defaultdict(set)
    for row in identity:
        by_patient[row["patient_id"]].add(row["fold_patient_grouped"])
    if any(len(folds) != 1 for folds in by_patient.values()):
        raise AssertionError("True patient crosses grouped folds")
    corrected_split = CAP / "reproducibility/splits/patient-grouped-corrected-20260922.csv"
    with corrected_split.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["cohort", "sample_id", "patient_key", "label", "fold"], lineterminator="\n")
        writer.writeheader()
        writer.writerows(dict(cohort=r["cohort"], sample_id=r["sample_id"], patient_key=r["patient_id"],
                              label=r["y"], fold=r["fold_patient_grouped"]) for r in identity)

    pairs = []
    for cohort in COHORTS:
        subset = [r for r in identity if r["cohort"] == cohort]
        patients = defaultdict(set)
        for r in subset:
            patients[r["patient_id"]].add(int(r["y"]))
        pairs.append(dict(cohort=cohort, n_samples=len(subset),
                          n_tumor=sum(int(r["y"]) for r in subset),
                          n_normal=sum(int(r["y"]) == 0 for r in subset),
                          n_patients=len(patients),
                          n_paired_patients=sum(v == {0, 1} for v in patients.values()),
                          n_tumor_only_patients=sum(v == {1} for v in patients.values()),
                          n_normal_only_patients=sum(v == {0} for v in patients.values())))
    write("b28_pair_counts.csv", pairs)
    tex("cohort_rows.tex", [f"{r['cohort'].upper()} & {r['n_samples']} & "
                            f"{r['n_tumor']}/{r['n_normal']} & {r['n_patients']} & "
                            f"{r['n_paired_patients']} \\\\" for r in pairs] +
                           [r"\hline", r"Total & 1191 & 689/502 & 719 & 470 \\"])

    transfer = []
    for c in COHORTS:
        transfer.append(dict(cohort=c, auc_abundance=logo["by_cohort"][c]["auroc"],
                             auc_missingness=main_results["missingness"]["leave_one_cohort_out"]["by_cohort"][c]["auroc"],
                             auc_trivial=main_results["global_summaries"]["leave_one_cohort_out"]["by_cohort"][c]["auroc"],
                             ece_abundance=logo["by_cohort"][c]["ece_10"]))
    write("b28_transfer.csv", transfer)
    labels = {"missingness": "missingness mask only", "global_summaries": "global summaries (3 features)",
              "accession": "abundance (8906 accessions)"}
    write("b28_ladder.csv", [dict(arm=labels[k], auc=main_results[k]["leave_one_cohort_out"]["pooled"]["auroc"],
                                macro_auc=main_results[k]["leave_one_cohort_out"]["macro_equal_cohort"]["auroc"],
                                ece=main_results[k]["leave_one_cohort_out"]["pooled"]["ece_10"])
                             for k in labels])
    protocols, reliability, ece_rows, summary_rows = [], [], [], []
    for protocol, short in PROTOCOLS.items():
        rows = [r for r in pred if r["feature_set"] == "accession" and r["protocol"] == protocol]
        pooled = metrics(rows)
        stored = main_results["accession"][protocol]
        assert abs(pooled["auc"]-stored["pooled"]["auroc"]) < 1e-12
        for fold in sorted({r["fold"] for r in rows}):
            m = metrics([r for r in rows if r["fold"] == fold])
            protocols.append(dict(protocol=short, fold_id=fold, n=m["n"], auc=m["auc"], ece=m["ece"],
                                  pooled_auc="", pooled_ece=""))
        protocols.append(dict(protocol=short, fold_id="pooled", n=pooled["n"], auc="", ece="",
                              pooled_auc=pooled["auc"], pooled_ece=pooled["ece"]))
        label = {"sample_random": "Sample CV", "patient_grouped": "Patient CV", "leave_one_cohort_out": "LOGO"}[protocol]
        summary_rows.append(f"{label} & {stored['macro_equal_cohort']['auroc']:.4f} & {pooled['auc']:.4f} & "
                            f"{stored['macro_equal_cohort']['ece_10']:.4f} & {pooled['ece']:.4f} \\\\")
        ece_rows.append(dict(eval=label, ece=pooled["ece"], auc=pooled["auc"]))
        if protocol == "patient_grouped":
            continue
        method = "random 5-fold (mixes cohorts)" if protocol == "sample_random" else "LOGO (grouped, honest)"
        y = np.array([int(r["y"]) for r in rows])
        p = np.array([float(r["p"]) for r in rows])
        for j in range(10):
            mask = (p >= j/10) & ((p < (j+1)/10) if j < 9 else (p <= 1))
            if mask.any():
                reliability.append(dict(method=method, bin=j, n=int(mask.sum()),
                                        conf=float(p[mask].mean()), acc=float(y[mask].mean())))
    write("b28_protocol_summary.csv", protocols)
    write("b28_reliability.csv", reliability)
    write("b28_ece_compare.csv", ece_rows)
    tex("protocol_rows.tex", summary_rows)
    write("b28_riskcoverage.csv", [dict(coverage=r["coverage"], retained_acc_conf=r["accuracy_retained"], full_acc=r["accuracy_full"])
                                   for r in risk])
    composition = [dict(coverage=r["coverage"], n_retained=r["n_retained"],
                        **{c: int(r[f"n_{c}"])/int(r["n_retained"]) for c in COHORTS}) for r in risk]
    write("b28_riskcoverage_cohort.csv", composition)
    tex("coverage_rows.tex", [f"{float(r['coverage']):.1f} & {r['n_retained']} & " +
                              " & ".join(f"{r[c]:.3f}" for c in COHORTS) + r" \\" for r in composition])

    for arm, fname, first, second in (("train_median_l2", "b28_l2_vs_xgb.csv", "xgb", "l2"),
                                    ("full_data_median_leak_xgb", "b28_leaky_compare.csv", "honest", "leaky")):
        output = []
        for c in (*COHORTS, "pooled"):
            a = logo["pooled"] if c == "pooled" else logo["by_cohort"][c]
            b = sides["results"][arm]["pooled"] if c == "pooled" else sides["results"][arm]["by_cohort"][c]
            output.append(dict(cohort=c, **{f"auc_{first}": a["auroc"], f"auc_{second}": b["auroc"],
                                          f"ece_{first}": a["ece_10"], f"ece_{second}": b["ece_10"]}))
        write(fname, output)
    rec_rows = []
    for fold in rec["folds"]:
        m = fold["metrics"]
        rec_rows.append(dict(cohort=fold["held_out"], n=m["before"]["n"], auc=m["before"]["auroc"],
                             ece_before=m["before"]["ece_10"], T=fold["fitted_temperature"],
                             ece_after_temperature=m["temperature"]["ece_10"], ece_after_platt=m["platt"]["ece_10"]))
    pooled_rec = {k: metrics(recal, f"p_{k}") for k in ("before", "temperature", "platt")}
    rec_rows.append(dict(cohort="pooled", n=len(recal), auc=pooled_rec["before"]["auc"],
                         ece_before=pooled_rec["before"]["ece"], T="",
                         ece_after_temperature=pooled_rec["temperature"]["ece"], ece_after_platt=pooled_rec["platt"]["ece"]))
    write("b28_recal_summary.csv", rec_rows)
    write("b28_recal_scores.csv", recal)
    tex("recalibration_rows.tex", [f"{r['cohort'].upper()} & {r['ece_before']:.4f} & "
                                   f"{r['ece_after_temperature']:.4f} & {r['ece_after_platt']:.4f}" + r" \\" for r in rec_rows])
    detail = []
    for key in ("accession", "global_summaries", "missingness", "consistent_gene_first_sensitivity"):
        for c in COHORTS:
            m = main_results[key]["leave_one_cohort_out"]["by_cohort"][c]
            detail.append(dict(arm=key, cohort=c, **m))
    for key, data in sides["results"].items():
        detail.extend(dict(arm=key, cohort=c, **data["by_cohort"][c]) for c in COHORTS)
    write("b28_all_cohort_metrics.csv", detail)
    for arm, fname in (("accession", "primary_rows.tex"), ("global_summaries", "global_rows.tex"),
                       ("missingness", "missingness_rows.tex"), ("consistent_gene_first_sensitivity", "mapping_rows.tex"),
                       ("train_median_l2", "l2_rows.tex"), ("full_data_median_leak_xgb", "leaky_rows.tex")):
        tex(fname, [f"{r['cohort'].upper()} & {r['auroc']:.4f} & {r['ece_10']:.4f} & "
                   f"{r['brier']:.4f} & {r['log_loss']:.4f}" + r" \\" for r in detail if r["arm"] == arm])
    sens = json.loads((BASE/"fixed-prediction-patient-resampling.json").read_text())
    sens_rows = []
    for metric in ("macro_equal_cohort", "pooled"):
        for contrast, values in sens["results"][metric]["contrasts"].items():
            lo, hi = values["conditional_percentile_range"]
            sens_rows.append(f"{'Macro' if metric == 'macro_equal_cohort' else 'Pooled'} & "
                             f"{contrast.replace('_', ' ')} & {values['point']:.4f} & {lo:.4f}--{hi:.4f} \\\\")
    tex("resampling_rows.tex", sens_rows)
    fit_rows = [f"{r['held_out'].upper()} & {r['iterations']} & 500 & Yes" + r" \\" for r in sides["fit_details"] if r["arm"] == "train_median_l2"]
    tex("l2_convergence_rows.tex", fit_rows)
    audit = dict(schema="b28-original-manuscript-integration-1", date="2026-09-23",
                 status="corrected evidence integrated; scientific HOLD", scientific_ready_attested=False,
                 samples=1191, tumor=689, normal=502, patients=719, primary_accessions=8906,
                 source_sha256={str(p.relative_to(CAP)): sha(p) for p in
                                [BASE/"candidate-results.json", BASE/"predictions.csv", BASE/"candidate-QA.json",
                                 BASE/"sample-identity-and-folds.csv", BASE/"candidate-riskcoverage.csv",
                                 BASE/"candidate-recalibration.csv", BASE/"candidate-recalibration-summary.json",
                                 BASE/"fixed-prediction-patient-resampling.json", SIDE/"results.json", SIDE/"QA.json"]},
                 generated_sha256={str(p.relative_to(CAP)): sha(p) for p in sorted(PD.glob("*.csv")) + sorted(TABLES.glob("*.tex")) + [corrected_split]})
    (MAN/"integration-data.json").write_text(json.dumps(audit, indent=2)+"\n")
    print("Promoted corrected B28 evidence to original plot-data and article/SI tables; no model fit")


if __name__ == "__main__":
    main()
